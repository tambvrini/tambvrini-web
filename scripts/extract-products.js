#!/usr/bin/env node
/**
 * Extract products from a live backend and write
 * frontend/src/data/products.js with the REAL catalog.
 *
 * Usage (from repo root):
 *   BACKEND_URL=https://example.com node scripts/extract-products.js
 *
 * Or with the URL from frontend/.env:
 *   node scripts/extract-products.js
 */

const fs = require("fs");
const path = require("path");

const BACKEND_URL =
  process.env.BACKEND_URL ||
  (() => {
    try {
      const env = fs.readFileSync(
        path.join(__dirname, "..", "frontend", ".env"),
        "utf8"
      );
      const m = env.match(/REACT_APP_BACKEND_URL=(.+)/);
      return m ? m[1].trim() : null;
    } catch {
      return null;
    }
  })();

if (!BACKEND_URL) {
  console.error("No BACKEND_URL found. Set BACKEND_URL env or check frontend/.env");
  process.exit(1);
}

const API = `${BACKEND_URL}/api`;

async function main() {
  console.log(`Fetching products from ${API}/products?limit=100`);
  const res = await fetch(`${API}/products?limit=100`);
  if (!res.ok) throw new Error(`HTTP ${res.status}: ${await res.text()}`);
  const data = await res.json();
  const products = data.products || data;

  console.log(`Received ${products.length} products`);

  const fields = [
    "product_id",
    "name",
    "description",
    "price",
    "currency",
    "images",
    "thumbnail_image",
    "category",
    "gender",
    "sizes",
    "colors",
    "composition",
    "care",
    "is_new",
    "is_featured",
    "is_sold_out",
    "sold_out_sizes",
    "collections",
    "seo_title",
    "created_at",
  ];

  const cleaned = products.map((p) => {
    const obj = {};
    for (const k of fields) {
      if (p[k] !== undefined && p[k] !== null) obj[k] = p[k];
    }
    return obj;
  });

  const js = `/**
 * TAMBVRINI — Real product catalog cloned from the live Emergent backend.
 * Auto-generated by scripts/extract-products.js on ${new Date().toISOString()}.
 * Source: ${API}/products
 *
 * DO NOT EDIT MANUALLY — re-run the extraction script to update.
 */

const products = ${JSON.stringify(cleaned, null, 2)};

export default products;
`;

  const outPath = path.join(
    __dirname,
    "..",
    "frontend",
    "src",
    "data",
    "products.js"
  );
  fs.writeFileSync(outPath, js, "utf8");

  console.log(`Wrote ${outPath}`);
  console.log(`${cleaned.length} products, ${cleaned.filter((p) => (p.images || []).length > 0).length} with images`);

  for (const p of cleaned) {
    const imgs = (p.images || []).length;
    const thumb = p.thumbnail_image ? "Y" : "N";
    console.log(`  ${p.product_id.padEnd(30)} imgs=${imgs}  thumb=${thumb}  ${p.price} ${p.currency || 'EUR'}`);
  }
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
